import networkx as nx
# Импортируем библиотеку NetworkX для работы с графами

def generate_graph(n, p):
    # Функция для генерации случайного графа по модели Эрдёша–Реньи

    G = nx.erdos_renyi_graph(n, p)
    # Создаём граф с n вершинами, где вероятность появления ребра равна p

    return G
    # Возвращаем сгенерированный граф


def compute_average_degree(G):
    # Функция для вычисления средней степени вершины (экспериментальное значение)

    degrees = [deg for node, deg in G.degree()]
    # Получаем список степеней всех вершин графа

    avg_degree = sum(degrees) / len(degrees)
    # Вычисляем среднее значение степени

    return avg_degree
    # Возвращаем среднюю степень


def compute_theoretical_degree(n, p):
    # Функция для вычисления теоретической средней степени вершины

    return p * (n - 1)
    # Используем формулу из модели Эрдёша–Реньи


def main():
    # Основная функция программы

    n = 42
    # Количество вершин (задано преподавателем)

    p = 0.65
    # Вероятность появления ребра (задана преподавателем)

    G = generate_graph(n, p)
    # Генерируем граф

    avg_degree_exp = compute_average_degree(G)
    # Вычисляем экспериментальную среднюю степень

    avg_degree_theor = compute_theoretical_degree(n, p)
    # Вычисляем теоретическую среднюю степень

    print("Количество вершин графа:", n)
    # Выводим количество вершин

    print("Вероятность появления ребра p:", p)
    # Выводим вероятность

    print("Экспериментальное значение средней степени вершины:", avg_degree_exp)
    # Выводим экспериментальное значение

    print("Теоретическое значение средней степени вершины:", avg_degree_theor)
    # Выводим теоретическое значение

    print("Абсолютное отклонение между экспериментальным и теоретическим значениями:", abs(avg_degree_exp - avg_degree_theor))
    # Выводим разницу между значениями


if __name__ == "__main__":
    # Точка входа в программу

    main()
    # Запуск основной функции